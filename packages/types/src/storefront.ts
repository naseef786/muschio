import { z } from "zod";
export const StorefrontProductSchema = z.object({
  id: z.string(),
  slug: z.string().min(1),
  nameEn: z.string(),
  nameAr: z.string(),
  descriptionEn: z.string(),
  descriptionAr: z.string(),
  concentration: z.string(),
  brand: z.object({
    name: z.string(),
    slug: z.string(),
    type: z.string(),
    countryOfOrigin: z.string().nullable().optional(),
  }),
  scentFamily: z
    .object({ slug: z.string(), nameEn: z.string(), nameAr: z.string() })
    .nullable(),
  perfumer: z.string().nullable().optional(),
  perfumerBio: z.string().nullable().optional(),
  countryOfOrigin: z.string().nullable().optional(),
  origin: z.string().nullable().optional(),
  sillage: z.string().nullable().optional(),
  longevity: z.string().nullable().optional(),
  ratingAverage: z.number().nullable().optional(),
  ratingCount: z.number().nullable().optional(),
  images: z.array(z.string()),
  gender: z.string(),
  variants: z.array(
    z.object({
      id: z.string(),
      sku: z.string(),
      volume: z.union([z.string(), z.number()]).optional().transform((v) => (v !== undefined && v !== null ? (typeof v === "number" ? `${v}ml` : v) : undefined)),
      volumeMl: z.coerce.number().nullable().optional(),
      sizeLabelEn: z.string().optional(),
      sizeLabelAr: z.string().optional(),
      basePrice: z.coerce.number().nonnegative().optional().nullable(),
      regularPrice: z.coerce.number().nonnegative().optional(),
      originalPrice: z.coerce.number().nonnegative().optional(),
      price: z.coerce.number().nonnegative(),
      discountPrice: z.coerce.number().nullable().optional(),
      salePrice: z.coerce.number().nullable().optional(),
      compareAtPrice: z.coerce.number().nullable().optional(),
      isSampleVial: z.boolean().default(false),
      stock: z.coerce.number().int().nonnegative().optional(),
      stockQuantity: z.coerce.number().int().nonnegative().optional(),
      availableQuantity: z.coerce.number().int().nonnegative().default(10),
      warehouse: z.string().optional(),
      isDefault: z.boolean().default(false),
    }),
  ),
  notes: z.array(
    z.object({
      nameEn: z.string(),
      nameAr: z.string(),
      position: z.enum(["TOP", "HEART", "BASE"]),
      slug: z.string(),
    }),
  ),
});
export type StorefrontProduct = z.infer<typeof StorefrontProductSchema>;
export const StorefrontOrderSchema = z.object({
  id: z.string().uuid(),
  orderNumber: z.string(),
  status: z.string(),
  currency: z.literal("AED"),
  totalAmount: z.number().nonnegative(),
  paymentStatus: z.string().nullable().optional(),
  customerName: z.string().nullable().optional(),
  customerEmail: z.string().nullable().optional(),
  customerPhone: z.string().nullable().optional(),
  carrier: z.string().nullable().optional(),
  trackingNumber: z.string().nullable().optional(),
  estimatedDelivery: z.string().nullable().optional(),
  shippingAddress: z.any().nullable().optional(),
  createdAt: z.string().optional(),
  updatedAt: z.string().optional(),
  events: z.array(z.any()).optional(),
  items: z.array(
    z.object({
      id: z.string(),
      productNameEn: z.string(),
      productNameAr: z.string(),
      quantity: z.number().int().positive(),
      sizeLabel: z.string().nullable().optional(),
      totalPrice: z.number().nonnegative(),
      image: z.string().nullable().optional(),
      slug: z.string().nullable().optional(),
      brandName: z.string().nullable().optional(),
      unitPrice: z.number().nullable().optional(),
    }),
  ),
});
export type StorefrontOrder = z.infer<typeof StorefrontOrderSchema>;
